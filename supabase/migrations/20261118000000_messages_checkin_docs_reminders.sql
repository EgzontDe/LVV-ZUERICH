-- 1) Messages / requests between members and the board
create table public.requests (
  id         bigint primary key,
  member_id  bigint references public.members (id) on delete cascade,
  status     text not null default 'pret' check (status in ('pret','u_pergjigj','mbyllur')),
  extra      jsonb not null default '{}'::jsonb,   -- type, msg, date, reply, from, email
  created_at timestamptz not null default now()
);
create index requests_member_id_idx on public.requests (member_id);
alter table public.requests enable row level security;

create policy "requests: admin or own read" on public.requests for select to authenticated
  using ((select private.is_admin()) or member_id = (select private.my_member_id()));
create policy "requests: member sends own" on public.requests for insert to authenticated
  with check (member_id = (select private.my_member_id()) and status = 'pret' and coalesce(extra ->> 'reply', '') = '');
create policy "requests: admin update" on public.requests for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "requests: admin delete" on public.requests for delete to authenticated
  using ((select private.is_admin()));

-- 2) Event check-ins (who actually came)
create table public.event_checkins (
  event_id   bigint not null references public.events (id) on delete cascade,
  member_id  bigint not null references public.members (id) on delete cascade,
  checked_at timestamptz not null default now(),
  checked_by uuid default auth.uid(),
  primary key (event_id, member_id)
);
create index event_checkins_member_id_idx on public.event_checkins (member_id);
alter table public.event_checkins enable row level security;

create policy "checkins: admin or own read" on public.event_checkins for select to authenticated
  using ((select private.is_admin()) or member_id = (select private.my_member_id()));
create policy "checkins: admin insert" on public.event_checkins for insert to authenticated
  with check ((select private.is_admin()));
create policy "checkins: admin delete" on public.event_checkins for delete to authenticated
  using ((select private.is_admin()));

-- 3) Documents (PDF minutes, statutes) stored in a private bucket
create table public.documents (
  id         bigint generated by default as identity primary key,
  title      text not null check (length(title) between 2 and 200),
  kind       text not null default 'dokument' check (kind in ('procesverbal','dokument')),
  path       text not null unique,
  size_bytes bigint,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
alter table public.documents enable row level security;

create policy "documents: read" on public.documents for select to authenticated using (true);
create policy "documents: admin insert" on public.documents for insert to authenticated with check ((select private.is_admin()));
create policy "documents: admin delete" on public.documents for delete to authenticated using ((select private.is_admin()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('documents', 'documents', false, 10485760, array['application/pdf','image/png','image/jpeg']);

create policy "documents bucket: read" on storage.objects for select to authenticated
  using (bucket_id = 'documents');
create policy "documents bucket: admin upload" on storage.objects for insert to authenticated
  with check (bucket_id = 'documents' and (select private.is_admin()));
create policy "documents bucket: admin delete" on storage.objects for delete to authenticated
  using (bucket_id = 'documents' and (select private.is_admin()));

-- 4) In-app notifications (payment reminders)
create table public.notifications (
  id         bigint generated by default as identity primary key,
  member_id  bigint not null references public.members (id) on delete cascade,
  kind       text not null default 'kujtese_pagese',
  title      text not null,
  body       text not null default '',
  read_at    timestamptz,
  created_at timestamptz not null default now()
);
create index notifications_member_id_idx on public.notifications (member_id);
alter table public.notifications enable row level security;

create policy "notifications: admin or own read" on public.notifications for select to authenticated
  using ((select private.is_admin()) or member_id = (select private.my_member_id()));
create policy "notifications: admin insert" on public.notifications for insert to authenticated
  with check ((select private.is_admin()));
create policy "notifications: admin delete" on public.notifications for delete to authenticated
  using ((select private.is_admin()));

-- Members mark their own notifications as read (only read_at changes).
create or replace function public.mark_my_notifications_read()
returns void language plpgsql security definer set search_path = '' as $$
declare mid bigint := private.my_member_id();
begin
  if mid is null then return; end if;
  update public.notifications set read_at = now() where member_id = mid and read_at is null;
end; $$;
revoke execute on function public.mark_my_notifications_read() from public, anon;
grant execute on function public.mark_my_notifications_read() to authenticated;
