-- Core data for the platform. Each table keeps the fields used for access rules
-- and logic as real columns; everything else the UI stores lives in `extra` (jsonb).

create schema if not exists private;

-- ── Tables ──────────────────────────────────────────────────────────────────
create table public.members (
  id      bigint primary key,
  name    text not null,
  email   text not null,
  status  text not null default 'aktiv',
  pay     text not null default 'papaguar' check (pay in ('paguar','papaguar','liruar')),
  extra   jsonb not null default '{}'::jsonb
);
create unique index members_email_key on public.members (lower(email));

create table public.events (
  id      bigint primary key,
  title   text not null,
  public  boolean not null default false,
  rsvp    bigint[] not null default '{}',
  extra   jsonb not null default '{}'::jsonb
);

create table public.announcements (
  id      bigint primary key,
  title   text not null,
  extra   jsonb not null default '{}'::jsonb
);

create table public.polls (
  id        bigint primary key,
  question  text not null,
  status    text not null default 'aktiv' check (status in ('aktiv','mbyllur')),
  yes       integer not null default 0,
  no        integer not null default 0,
  abstain   integer not null default 0,
  voted     bigint[] not null default '{}',
  extra     jsonb not null default '{}'::jsonb
);

create table public.applications (
  id      bigint primary key,
  name    text not null check (length(name) between 2 and 120),
  email   text not null check (length(email) between 5 and 200),
  status  text not null default 'aplikim',
  extra   jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.donations (
  id         bigint primary key,
  amount     numeric(10,2) not null check (amount >= 5),
  member_id  bigint references public.members (id) on delete set null,
  extra      jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index donations_member_id_idx on public.donations (member_id);

create table public.payments (
  id         bigint generated by default as identity primary key,
  member_id  bigint not null references public.members (id) on delete cascade,
  year       integer not null,
  amount     numeric(10,2) not null check (amount >= 0),
  method     text not null default 'twint',
  status     text not null default 'ne_pritje' check (status in ('ne_pritje','konfirmuar','refuzuar')),
  created_at timestamptz not null default now()
);
create index payments_member_id_idx on public.payments (member_id);

-- ── Helpers (private schema: not callable through the API) ──────────────────
create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

create or replace function private.my_member_id()
returns bigint language sql stable security definer set search_path = '' as $$
  select id from public.members where lower(email) = lower((select auth.jwt()) ->> 'email') limit 1;
$$;

grant usage on schema private to authenticated;
grant execute on function private.is_admin(), private.my_member_id() to authenticated;

-- ── Row level security ──────────────────────────────────────────────────────
alter table public.members       enable row level security;
alter table public.events        enable row level security;
alter table public.announcements enable row level security;
alter table public.polls         enable row level security;
alter table public.applications  enable row level security;
alter table public.donations     enable row level security;
alter table public.payments      enable row level security;

-- members: admins everything, a member only their own row (read)
create policy "members: admin or self read" on public.members for select to authenticated
  using ((select private.is_admin()) or id = (select private.my_member_id()));
create policy "members: admin insert" on public.members for insert to authenticated
  with check ((select private.is_admin()));
create policy "members: admin update" on public.members for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "members: admin delete" on public.members for delete to authenticated
  using ((select private.is_admin()));

-- events / announcements / polls: every logged-in user reads, admins write
create policy "events: read" on public.events for select to authenticated using (true);
create policy "events: admin insert" on public.events for insert to authenticated with check ((select private.is_admin()));
create policy "events: admin update" on public.events for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "events: admin delete" on public.events for delete to authenticated using ((select private.is_admin()));

create policy "announcements: read" on public.announcements for select to authenticated using (true);
create policy "announcements: admin insert" on public.announcements for insert to authenticated with check ((select private.is_admin()));
create policy "announcements: admin update" on public.announcements for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "announcements: admin delete" on public.announcements for delete to authenticated using ((select private.is_admin()));

create policy "polls: read" on public.polls for select to authenticated using (true);
create policy "polls: admin insert" on public.polls for insert to authenticated with check ((select private.is_admin()));
create policy "polls: admin update" on public.polls for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "polls: admin delete" on public.polls for delete to authenticated using ((select private.is_admin()));

-- applications: anyone (also not logged in) can submit a new one; only admins see/manage
create policy "applications: public submit" on public.applications for insert to anon, authenticated
  with check (status = 'aplikim');
create policy "applications: admin read" on public.applications for select to authenticated using ((select private.is_admin()));
create policy "applications: admin update" on public.applications for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "applications: admin delete" on public.applications for delete to authenticated using ((select private.is_admin()));

-- donations: logged-in users read the donor list; members donate as themselves, admins record any
create policy "donations: read" on public.donations for select to authenticated using (true);
create policy "donations: insert" on public.donations for insert to authenticated
  with check ((select private.is_admin()) or member_id = (select private.my_member_id()));
create policy "donations: admin delete" on public.donations for delete to authenticated using ((select private.is_admin()));

-- payments: member sees own and can report a payment (pending); admins see and confirm all
create policy "payments: admin or own read" on public.payments for select to authenticated
  using ((select private.is_admin()) or member_id = (select private.my_member_id()));
create policy "payments: member reports own" on public.payments for insert to authenticated
  with check ((select private.is_admin()) or (member_id = (select private.my_member_id()) and status = 'ne_pritje'));
create policy "payments: admin update" on public.payments for update to authenticated
  using ((select private.is_admin())) with check ((select private.is_admin()));

-- ── Member actions that touch shared rows go through these functions ────────
create or replace function public.set_rsvp(p_event bigint, p_going boolean)
returns void language plpgsql security definer set search_path = '' as $$
declare mid bigint := private.my_member_id();
begin
  if mid is null then raise exception 'no member record for this account'; end if;
  update public.events
     set rsvp = case when p_going then array_append(array_remove(rsvp, mid), mid) else array_remove(rsvp, mid) end
   where id = p_event;
end; $$;

create or replace function public.cast_vote(p_poll bigint, p_choice text)
returns void language plpgsql security definer set search_path = '' as $$
declare mid bigint := private.my_member_id();
begin
  if mid is null then raise exception 'no member record for this account'; end if;
  if p_choice not in ('yes','no','abstain') then raise exception 'invalid choice'; end if;
  update public.polls
     set yes = yes + (p_choice = 'yes')::int,
         no = no + (p_choice = 'no')::int,
         abstain = abstain + (p_choice = 'abstain')::int,
         voted = array_append(voted, mid)
   where id = p_poll and status = 'aktiv' and not (mid = any(voted));
  if not found then raise exception 'poll closed or already voted'; end if;
end; $$;

create or replace function public.update_my_phone(p_phone text)
returns void language plpgsql security definer set search_path = '' as $$
declare mid bigint := private.my_member_id();
begin
  if mid is null then raise exception 'no member record for this account'; end if;
  if length(p_phone) > 40 then raise exception 'phone too long'; end if;
  update public.members set extra = jsonb_set(extra, '{phone}', to_jsonb(p_phone)) where id = mid;
end; $$;

revoke execute on function public.set_rsvp(bigint, boolean), public.cast_vote(bigint, text), public.update_my_phone(text) from public, anon;
grant execute on function public.set_rsvp(bigint, boolean), public.cast_vote(bigint, text), public.update_my_phone(text) to authenticated;
